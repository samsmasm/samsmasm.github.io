// Rebuilds the generated data block in index.html from data/defs.json.
// Run: node definitions/build.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const UNITS = {
  1: 'Unit 1: Introduction to business management',
  2: 'Unit 2: Human resource management',
  3: 'Unit 3: Finance and accounts',
  4: 'Unit 4: Marketing',
  5: 'Unit 5: Operations management',
  6: 'Toolkit and concepts',
};

const defs = JSON.parse(readFileSync(join(here, 'data/defs.json'), 'utf8'));
const problems = [];
defs.forEach((d, i) => {
  if (!d.term || !d.topic || !UNITS[d.unit]) problems.push(`#${i} ${d.term}: missing term, topic or unit`);
  if (!Array.isArray(d.p) || d.p.length < 2 || d.p.length > 3) problems.push(`#${i} ${d.term}: needs 2 or 3 parts`);
  if (JSON.stringify(d).includes('—')) problems.push(`#${i} ${d.term}: em dash`);
});
if (problems.length) { console.error(problems.join('\n')); process.exit(1); }

const BEGIN = '// BEGIN DATA (generated by build.mjs from data/defs.json, do not edit by hand)';
const END = '// END DATA';
const block = `${BEGIN}\nconst UNITS = ${JSON.stringify(UNITS)};\nconst DEFS = ${JSON.stringify(defs)};\n${END}`;

const file = join(here, 'index.html');
const html = readFileSync(file, 'utf8');
const a = html.indexOf(BEGIN), b = html.indexOf(END);
if (a < 0 || b < 0) { console.error('Data markers not found in index.html'); process.exit(1); }
writeFileSync(file, html.slice(0, a) + block + html.slice(b + END.length));
console.log(`Wrote ${defs.length} definitions into index.html`);
