// Builds business/index.html and economics/index.html from template.html and data/<subject>.json.
// Run: node definitions/build.mjs   (never hand-edit the generated pages)
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const SUBJECTS = {
  business: {
    name: 'Business Management', colour: '#1a3a7a',
    lede: 'Three terms, eight pieces, two of them spares. Put two pieces under each term, in order.',
    minParts: 2,
    units: {
      1: 'Unit 1: Introduction to business management',
      2: 'Unit 2: Human resource management',
      3: 'Unit 3: Finance and accounts',
      4: 'Unit 4: Marketing',
      5: 'Unit 5: Operations management',
      6: 'Toolkit and concepts',
    },
  },
  economics: {
    name: 'Economics', colour: '#145c34',
    lede: 'Three terms and their pieces, plus two spares. Put the pieces under each term, in order.',
    minParts: 1,   // 5 terms are one idea and get a single box
    units: {
      1: 'Unit 1: Introduction to economics',
      2: 'Unit 2: Microeconomics',
      3: 'Unit 3: Macroeconomics',
      4: 'Unit 4: The global economy',
    },
  },
};

const template = readFileSync(join(here, 'template.html'), 'utf8');
let failed = false;
for (const [slug, s] of Object.entries(SUBJECTS)) {
  const defs = JSON.parse(readFileSync(join(here, `data/${slug}.json`), 'utf8'));
  const problems = [];
  defs.forEach((d, i) => {
    if (!d.term || !d.topic || !s.units[d.unit]) problems.push(`#${i} ${d.term}: missing term, topic or unit`);
    if (!Array.isArray(d.p) || d.p.length < s.minParts || d.p.length > 3) problems.push(`#${i} ${d.term}: wrong number of parts`);
    if (/[—–]/.test(JSON.stringify(d))) problems.push(`#${i} ${d.term}: em or en dash`);
  });
  if (problems.length) { console.error(`${slug}:\n  ` + problems.join('\n  ')); failed = true; continue; }
  const block = `// BEGIN DATA (generated by build.mjs from data/${slug}.json, do not edit by hand)\n`
    + `const UNITS = ${JSON.stringify(s.units)};\nconst DEFS = ${JSON.stringify(defs)};\n// END DATA`;
  const html = template
    .replaceAll('{{SUBJECT}}', s.name).replace('{{SLUG}}', slug).replace('{{COLOUR}}', s.colour).replace('{{LEDE}}', s.lede)
    .replace('{{DATA}}', () => block);
  if (/\{\{[A-Z]+\}\}/.test(html)) { console.error(`${slug}: placeholder left in output`); failed = true; continue; }
  mkdirSync(join(here, slug), { recursive: true });
  writeFileSync(join(here, slug, 'index.html'), html);
  console.log(`Wrote ${defs.length} definitions into ${slug}/index.html`);
}
if (failed) process.exit(1);
